import {chromium} from 'playwright'
import {writeFile} from 'node:fs/promises'
import assert from 'node:assert/strict'
const browser=await chromium.connectOverCDP('http://127.0.0.1:9222')
try {
 const page=browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('#/home/'))
 if(await page.locator('.plugin-native-modal').count())await page.locator('.plugin-native-modal .t-dialog__close').click()
 const section=page.getByRole('region',{name:'网易云歌单'})
 if(!page.url().includes('/home/songlist'))await page.getByRole('button',{name:/歌单$/}).first().click()
 await section.locator('.playlist-open').first().click()
 await page.waitForURL(/#\/home\/list\//)
 await page.waitForFunction(()=>document.querySelectorAll('.song-item,.song-row,.music-list-item').length>0 || document.body.innerText.includes('播放全部'))
 const detail=await page.evaluate(()=>({route:location.hash,frames:document.querySelectorAll('iframe,webview').length}))
 const ref=JSON.parse(new URLSearchParams(detail.route.split('?')[1]).get('resourceRef'))
 assert.equal(ref.providerId,'wy')
 assert.equal(ref.pluginId,'ceru.netease-account')
 assert.equal(detail.frames,0)
 await page.getByRole('button',{name:/歌单$/}).first().click()
 await section.locator('.playlist-card').first().waitFor()
 await section.evaluate(el=>el.scrollIntoView({block:'start'}))
 await page.screenshot({path:'G:/code/CeruMusic/.tmp-plugin-tooling-031/live-inline-playlists.png'})
 await page.evaluate(()=>window.api.plugins.openSurface('9832c5669052ac6dc0016bd42fea07f6','account'))
 const modal=page.locator('.plugin-native-modal')
 const frame=page.frameLocator('iframe[title="网易云账号"]')
 await frame.getByRole('button',{name:'退出网易云账号',exact:true}).waitFor({timeout:15000})
 await page.waitForFunction(()=>document.querySelector('.plugin-native-modal .t-dialog__body')?.getBoundingClientRect().height < 220)
 const dimensions=await frame.locator('body').evaluate(el=>({height:innerHeight,width:innerWidth,scrollHeight:el.scrollHeight,scrollWidth:el.scrollWidth}))
 assert.ok(dimensions.scrollHeight<=dimensions.height+1)
 assert.ok(dimensions.scrollWidth<=dimensions.width+1)
 await page.screenshot({path:'G:/code/CeruMusic/.tmp-plugin-tooling-031/live-compact-account.png'})
 await modal.locator('.t-dialog__close').click()
 await writeFile('G:/code/CeruMusic/.tmp-plugin-tooling-031/live-final-result.json',JSON.stringify({detail,dimensions},null,2))
 console.log({detail,dimensions})
} finally {await browser.close()}
