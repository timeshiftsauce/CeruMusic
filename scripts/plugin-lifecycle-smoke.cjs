const { app, BrowserWindow } = require('electron')
const { mkdtemp, writeFile, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const assert = require('node:assert/strict')
app.whenReady().then(async () => {
  const root = await mkdtemp(join(tmpdir(), 'ceru-lifecycle-'))
  app.setPath('userData', root)
  const { default: service } = await import('../.plugin-lifecycle-smoke.mjs')
  const window = new BrowserWindow({ show: false, webPreferences: { nodeIntegration: true, contextIsolation: false } })
  try {
    const page = join(root, 'bridge.html')
    // Trusted, isolated test page; production renderer security settings are unchanged.
    await writeFile(page, `<script>window.prompts=0;window.toasts=[];window.allow=true;require('electron').ipcRenderer.on('plugin:ui',(_,r)=>{if(r.method==='ui.permissions.request')window.prompts++;if(r.method==='ui.toast')window.toasts.push(r.data);require('electron').ipcRenderer.invoke('plugin:ui-result',{id:r.id,value:window.allow,error:window.failPrompt&&r.method==='ui.permissions.request'?'UI unavailable':undefined})})</script>`)
    await window.loadFile(page)
    const manifest = { manifestVersion: 2, id: 'test.lifecycle', name: 'Lifecycle', version: '1.0.0', engines: {hostApi:'^2.0.0',logicRuntime:'ceru-js@1'}, modules:{logic:{entry:'logic.main'}}, permissions:[{key:'network',name:'network.request',reason:'test'}], contributes:{commands:[{id:'grant',title:'Grant',action:'grant'},{id:'network',title:'Network',action:'network'}]} }
    const code = body => 'exports.manifest = ' + JSON.stringify(manifest) + '; exports.activate = async function(ctx) {' + body + '};'
    await service.initializePlugins()
    const broken = await service.addPlugin(code('throw new Error("activation sentinel")'), 'fixture.js')
    assert.equal(service.getPluginById(broken.pluginId), null, 'install does not execute code')
    await assert.rejects(service.setActivePlugin(broken.pluginId), /activation sentinel/)
    const valid = code('ctx.actions.register("grant", async () => ctx.permissions.request({key:"network"})); const bridge=ctx.modules.require("@ceru/legacy-http").createLegacyHttpBridge(ctx); ctx.actions.register("network",async (_,op)=>bridge.withOperation(op,async()=>bridge.httpFetch("https://example.test/denied").promise));')
    const item = await service.addPlugin(valid, 'fixture.js')
    assert.equal(service.getPluginById(item.pluginId), null)
    await service.setActivePlugin(item.pluginId)
    const grant = () => service.getPluginById(item.pluginId).invokeV2Action('grant')
    assert.equal((await grant()).status, 'granted')
    assert.equal((await grant()).status, 'granted')
    assert.equal(await window.webContents.executeJavaScript('window.prompts'), 1)
    await service.setActivePlugin(null)
    assert.equal(service.getPluginById(item.pluginId), null, 'close destroys runtime')
    await service.setActivePlugin(item.pluginId)
    assert.equal((await grant()).status, 'granted')
    assert.equal(await window.webContents.executeJavaScript('window.prompts'), 1, 'close/reuse preserves grant')
    await service.uninstallPlugin(item.pluginId)
    await service.addPlugin(valid, 'fixture.js')
    assert.equal(service.getPluginById(item.pluginId), null)
    await service.setActivePlugin(item.pluginId)
    assert.equal((await grant()).status, 'granted')
    assert.equal(await window.webContents.executeJavaScript('window.prompts'), 2, 'reinstall requests fresh grant')
    service.getPluginById(item.pluginId).setGrantedPermissions([])
    await window.webContents.executeJavaScript('window.allow=false')
    assert.equal((await grant()).status, 'denied')
    assert.equal((await grant()).status, 'denied')
    await assert.rejects(service.getPluginById(item.pluginId).invokeV2Action('network'), /网络访问未授权，请在插件权限中允许后重试/)
    const toasts = await window.webContents.executeJavaScript('window.toasts')
    assert.equal(toasts.length, 1, 'denied requests are explained without toast spam')
    assert.match(toasts[0].message, /权限中允许后重试/)
    service.getPluginById(item.pluginId).setGrantedPermissions([])
    await window.webContents.executeJavaScript('window.failPrompt=true')
    await assert.rejects(grant(), /UI unavailable/)
    await window.webContents.executeJavaScript('window.failPrompt=false;window.allow=true')
    assert.equal((await grant()).status, 'granted', 'failed UI transport does not suppress the next prompt')
    console.log('PASS: install without execution, use/close, retained grants and fresh permission prompt after reinstall')
  } catch (error) { console.error(error); process.exitCode = 1 }
  finally {
    await service.disposeAll()
    window.destroy()
    await rm(root, { recursive: true, force: true })
    app.exit(process.exitCode || 0)
  }
}).catch(error => { console.error(error); app.exit(1) })
